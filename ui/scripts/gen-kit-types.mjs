#!/usr/bin/env node
// gen-kit-types.mjs — regenerate ui/sdk/src/client.d.ts from the kit (DESIGN §37.3, §38.7).
//
// The kit is registered globally on core's Vue app, so a plugin writes `<CoreButton>` in a template
// with no import. TypeScript only knows that through `GlobalComponents`, which this script writes
// from the actual files in ui/src/kit/components — one entry per Core*.vue, plus the `*.vue` module
// shim every plugin needs. The output is COMMITTED (plugins consume it through
// `"types": ["@core/ui/client"]`, and a plugin checkout has no way to run this script).
//
//   node ui/scripts/gen-kit-types.mjs            rewrite the file
//   node ui/scripts/gen-kit-types.mjs --check    exit 1 when it is stale (check.sh / CI)

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const UI_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const COMPONENTS_DIR = path.join(UI_DIR, 'src/kit/components')
const OUT_FILE = path.join(UI_DIR, 'sdk/src/client.d.ts')
// How `sdk/src/client.d.ts` reaches the components — kept as a literal so the generated file is
// readable and stable no matter where the script is run from.
const REL = '../../src/kit/components'

function kitComponents() {
  if (!fs.existsSync(COMPONENTS_DIR)) {
    throw new Error(`[gen-kit-types] no kit components at ${COMPONENTS_DIR}`)
  }
  return fs
    .readdirSync(COMPONENTS_DIR)
    .filter((f) => /^Core[A-Za-z0-9]*\.vue$/.test(f))
    .map((f) => f.slice(0, -'.vue'.length))
    .sort()
}

function render(names) {
  const entries = names
    .map((n) => `    ${n}: typeof import('${REL}/${n}.vue')['default']`)
    .join('\n')
  return `// GENERATED by ui/scripts/gen-kit-types.mjs — do not edit. Run \`npm run gen:kit-types\`.
//
// What a plugin's TypeScript needs from core: the kit's ${names.length} globally registered
// components (DESIGN §37.5) and the \`*.vue\` module shim. Wired up by
// \`"types": ["@core/ui/client"]\` in @core/ui/tsconfig.plugin.json.

declare module 'vue' {
  export interface GlobalComponents {
${entries}
  }
}

declare module '*.vue' {
  import type { DefineComponent } from 'vue'
  const component: DefineComponent<Record<string, unknown>, Record<string, unknown>, unknown>
  export default component
}

export {}
`
}

const check = process.argv.includes('--check')
const names = kitComponents()
const next = render(names)
const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : null

if (check) {
  if (current === next) {
    console.log(`gen-kit-types: up to date (${names.length} kit components)`)
    process.exit(0)
  }
  console.error(
    `gen-kit-types: ${path.relative(UI_DIR, OUT_FILE)} is stale — run \`npm run gen:kit-types\` in core/ui and commit it.`,
  )
  if (current) {
    const has = new Set([...current.matchAll(/^\s{4}(Core[A-Za-z0-9]*):/gm)].map((m) => m[1]))
    const added = names.filter((n) => !has.has(n))
    const removed = [...has].filter((n) => !names.includes(n))
    if (added.length) console.error(`  missing: ${added.join(', ')}`)
    if (removed.length) console.error(`  gone:    ${removed.join(', ')}`)
  }
  process.exit(1)
}

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true })
fs.writeFileSync(OUT_FILE, next)
console.log(
  `gen-kit-types: wrote ${path.relative(UI_DIR, OUT_FILE)} (${names.length} kit components)${current === next ? ' — unchanged' : ''}`,
)
